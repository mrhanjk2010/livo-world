/**
 * 「世界背面」那三张流水卡的拍子。
 *
 * 每一行落下的间隔是随机的，不是定值。定值滚起来是节拍器：均匀、可预期，于是眼
 * 睛很快认出这是一段循环播放的动画，不再当它是正在发生的事。忽快忽慢才像那边真
 * 有一台机器在算 —— 有时一拍里连出三件事，有时半天没动静。
 *
 * 三张卡各自摇各自的骰子，所以它们不会一起往上顶：整屏看过去是此起彼伏的，而
 * 不是三行一起跳。
 */

export type TickRange = {
  min: number;
  max: number;
};

/**
 * 算的那张卡：快。
 *
 * 0.1–0.5 秒。这一张滚的是机器每一拍都在跑的账（调了哪个模型、花了多少毫秒），
 * 快到只读得清一两个词 —— 读不完是对的，它要表达的是「一直在算」这件事本身，不
 * 是某一行的内容。想读清哪一行就把这张卡点开。
 */
export const CALC_TICK: TickRange = { min: 100, max: 500 };

/**
 * 命运和因果那两张卡：慢。
 *
 * 1–5 秒。上界卡在 5 秒：再长就不像在跑，像卡住了。下界 1 秒：再短就来不及读完
 * 那一行 —— 这两张上滚的是一件件落下来的命运、一条条咬成的链，是要给人读完的。
 */
export const READ_TICK: TickRange = { min: 1000, max: 5000 };

/** 下一拍隔多久。 */
export function nextTickMs(range: TickRange): number {
  return range.min + Math.random() * (range.max - range.min);
}

/**
 * 顶一格最多滑多久。
 *
 * 拍子是「多久落下一行」，这个是「落下时那一下滑多快」。不跟着随机的拍子走：那
 * 样会变成有时滑得像在飘、有时像被弹上去。
 */
const SLIDE_MAX_MS = 220;

/**
 * 这一档拍子下，顶一格该滑多久。
 *
 * 必须滑得完 —— 拍子比这一下还短的话，上一格还没滑到位就被下一格从头接上，看到
 * 的是「平滑走一半、瞬间跳一半」的锯齿，比老老实实跳格更难看。所以快那一档
 * （最短 0.1 秒）把滑动压到 100ms：最急的那几拍刚好滑完，慢一点的拍子滑完了就停
 * 着等下一拍。
 */
export function slideMs(tick: TickRange): number {
  return Math.min(SLIDE_MAX_MS, tick.min);
}
