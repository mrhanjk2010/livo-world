/**
 * 「世界背面」那三张流水卡的拍子。
 *
 * 每一行落下的间隔是随机的（1–5 秒），不是定值。定值滚起来是节拍器：均匀、可
 * 预期，于是眼睛很快认出这是一段循环播放的动画，不再当它是正在发生的事。忽快
 * 忽慢才像那边真有一台机器在算 —— 有时一秒里连出三件事，有时四五秒没动静。
 *
 * 三张卡各自摇各自的骰子，所以它们不会一起往上顶：整屏看过去是此起彼伏的，而
 * 不是三行一起跳。
 *
 * 上界卡在 5 秒：再长就不像在跑，像卡住了。下界 1 秒：再短就来不及读完那一行，
 * 而现在这三张卡上滚的都是真话（真日志、真命运、真因果链），是要给人读的。
 */

export const TICK_MIN_MS = 1000;
export const TICK_MAX_MS = 5000;

/** 下一拍隔多久。 */
export function nextTickMs(): number {
  return TICK_MIN_MS + Math.random() * (TICK_MAX_MS - TICK_MIN_MS);
}

/**
 * 顶一格用多久。
 *
 * 和拍子无关的一个定值：拍子是「多久落下一行」，这个是「落下时那一下滑多快」。
 * 跟着随机的拍子走会变成有时滑得像在飘、有时像被弹上去。
 */
export const SLIDE_MS = 220;
