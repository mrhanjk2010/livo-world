/**
 * 「世界背面」那三张流水卡的拍子。
 *
 * 每一行落下的间隔是随机的，不是定值。定值滚起来是节拍器：均匀、可预期，于是眼
 * 睛很快认出这是一段循环播放的动画，不再当它是正在发生的事。忽快忽慢才像那边真
 * 有一台机器在算 —— 有时一拍里连出三件事，有时半天没动静。
 *
 * 三张卡各自摇各自的骰子，所以它们不会一起往上顶：整屏看过去是此起彼伏的，而
 * 不是三行一起跳。
 */

export type TickRange = {
  min: number;
  max: number;
};

/**
 * 算的那张卡：快。
 *
 * 0.2–1 秒。这一张滚的是机器每一拍都在跑的账（调了哪个模型、花了多少毫秒），快
 * 到只读得清一两个词 —— 读不完是对的，它要表达的是「一直在算」这件事本身，不是
 * 某一行的内容。想读清哪一行就把这张卡点开。
 */
export const CALC_TICK: TickRange = { min: 200, max: 1000 };

/**
 * 命运和因果那两张卡：慢。
 *
 * 1–5 秒。上界卡在 5 秒：再长就不像在跑，像卡住了。下界 1 秒：再短就来不及读完
 * 那一行 —— 这两张上滚的是一件件落下来的命运、一条条咬成的链，是要给人读完的。
 */
export const READ_TICK: TickRange = { min: 1000, max: 5000 };

/** 下一拍隔多久。 */
export function nextTickMs(range: TickRange): number {
  return range.min + Math.random() * (range.max - range.min);
}

/**
 * 顶一格用多久。
 *
 * 和拍子无关的一个定值：拍子是「多久落下一行」，这个是「落下时那一下滑多快」。
 * 跟着随机的拍子走会变成有时滑得像在飘、有时像被弹上去。
 *
 * 快那一档最短的拍子（200ms）比这一下还短，于是顶到一半就被下一格接上 —— 那时候
 * 看到的是连续往上淌，而不是一格一格地跳。在那个速度上这正是想要的：每 200ms 老
 * 老实实跳一格，看着是抽动。
 */
export const SLIDE_MS = 220;
